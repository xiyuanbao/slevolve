#!/usr/bin/env python3
"""
tools/prepare_case3_nadi.py -- build solver inputs for the Lucas et al. (2026) ICE-NADI-1
deglacial case (EGUsphere preprint egusphere-2026-4374).

Writes (all under the --out INPUT_FILES tree):
      icemodel/nadi_<k>          k = 0..50, k=0 at 25 ka BP, 512 lines x 1024 values
      others/topo_pres           present-day bedrock (etopo2_512_ice6gC of Han et al. 2022)
      grid/GLlat_512.txt         copied from --grid (generated by tools/make_grid.py if --grid is not given)
      grid/GLlon_512.txt
      earthmodel/prem_256.l96C.ump3.lm3.lucas      solver text layout, degrees 1..256 (optional,
                                                   only with --slcode; not used by Case 3)
      earthmodel/prem_256.l100C.ump2.lm1.lucas
      earthmodel/prem_256.l100C.ump4.lm1.lucas

Love-number conversion is the text layout the solver's reader expects
(block "Read in Love numbers" of fortran/src/sl_model_mod.f90).  The
SavedLN / SavedLN_EP .mat files of https://github.com/jaustermann/SLcode carry the
modal poles under the name `spoles` and hold 256 degrees.

Nothing outside the --out tree is written.
"""
import os
import sys
import argparse
import numpy as np

# Paths are set from the command line in main() (see --help).
TREE = None       # --out: output INPUT_FILES tree
NC_ICE = None     # --ice-nc: ICE-NADI-1.nc (Zenodo doi:10.5281/zenodo.21464139)
GRID_DIR = None   # --grid: directory with GLlat_512.txt, GLlon_512.txt (Han et al. 2022 OSF archive)
TOPO_SRC = None   # --topo: etopo2_512_ice6gC (Han et al. 2022 OSF archive)
LN_DIR = None     # --slcode: optional, SLcode directory with SavedLN/ and SavedLN_EP/ .mat files

NLAT = 512
NLON = 1024
MAXDEG_FILE = 256           # SavedLN / SavedLN_EP .mat files stop at degree 256
FMT = "%18.10E"

EARTH_MODELS = {
    # tag                       relative path under SLcode/            comment
    "l96C.ump3.lm3":  ("SavedLN/prem.l96C.ump3.lm3.mat",
                       "96 km lith, UM 3e20, LM 3e21"),
    "l100C.ump2.lm1": ("SavedLN_EP/prem.l100C.ump2.lm1.mat",
                       "100 km lith, UM 2e20, LM 1e21"),
    "l100C.ump4.lm1": ("SavedLN_EP/prem.l100C.ump4.lm1.mat",
                       "100 km lith, UM 4e20, LM 1e21"),
}


def emfile(tag):
    return "prem_%d.%s.lucas" % (MAXDEG_FILE, tag)


# ----------------------------------------------------------------- grid / ice
def write_grid_field(path, arr):
    assert arr.shape == (NLAT, NLON), arr.shape
    np.savetxt(path, arr, fmt=FMT, delimiter=" ")


def check_grid():
    import netCDF4 as nc
    d = nc.Dataset(NC_ICE)
    lat2 = np.asarray(d.variables["lat"][:])
    lon2 = np.asarray(d.variables["lon"][:])
    alat = np.loadtxt(os.path.join(GRID_DIR, "GLlat_512.txt"))
    alon = np.loadtxt(os.path.join(GRID_DIR, "GLlon_512.txt"))
    nlat = lat2[:, 0]
    nlon = lon2[0, :]
    print("  NADI lat[0]=%.6f  lat[-1]=%.6f  (north first: %s)"
          % (nlat[0], nlat[-1], nlat[0] > nlat[-1]))
    print("  archive lat[0]=%.6f  lat[-1]=%.6f" % (alat[0], alat[-1]))
    print("  max|lat_NADI - lat_archive| = %.3e deg  (float32 storage)"
          % np.abs(nlat - alat).max())
    print("  max|lon_NADI - lon_archive| = %.3e deg" % np.abs(nlon - alon).max())
    print("  lat constant along a row: %s" % (np.ptp(lat2, axis=1).max() == 0))
    assert np.abs(nlat - alat).max() < 1e-4
    assert np.abs(nlon - alon).max() < 1e-4
    d.close()


def write_ice():
    import netCDF4 as nc
    d = nc.Dataset(NC_ICE)
    t = np.asarray(d.variables["time"][:])
    ice = d.variables["ice_thickness"]
    print("  time[0]=%.1f ka  time[-1]=%.1f ka  n=%d  dt=%.2f kyr"
          % (t[0], t[-1], len(t), t[0] - t[1]))
    assert t[0] == 25.0 and t[-1] == 0.0 and len(t) == 51
    out = os.path.join(TREE, "icemodel")
    nnan = 0
    vols = []
    for k in range(len(t)):
        a = np.asarray(ice[k]).astype(float)
        nnan += int(np.isnan(a).sum())
        a = np.nan_to_num(a, nan=0.0)
        a[a < 0] = 0.0
        write_grid_field(os.path.join(out, "nadi_%d" % k), a)
        vols.append(a)
    print("  wrote 51 ice files, total NaNs replaced by 0: %d" % nnan)
    # round-trip check on one file
    b = np.loadtxt(os.path.join(out, "nadi_40"))
    a = np.nan_to_num(np.asarray(ice[40]).astype(float), nan=0.0)
    print("  round-trip nadi_40 max|d| = %.2e m" % np.abs(a - b).max())
    d.close()
    return vols


def write_topo():
    topo = np.loadtxt(TOPO_SRC)
    assert topo.shape == (NLAT, NLON), topo.shape
    write_grid_field(os.path.join(TREE, "others", "topo_pres"), topo)
    print("  topo_pres from %s : min %.1f max %.1f mean %.1f m"
          % (os.path.basename(TOPO_SRC), topo.min(), topo.max(), topo.mean()))
    return topo


def copy_grid():
    for f in ("GLlat_512.txt", "GLlon_512.txt"):
        src = os.path.join(GRID_DIR, f)
        dst = os.path.join(TREE, "grid", f)
        with open(src) as fi, open(dst, "w") as fo:
            fo.write(fi.read())
    print("  copied GLlat_512.txt / GLlon_512.txt")


# ------------------------------------------------------- Love-number converter
def build_earthmodel(ln, path, header, maxdeg=MAXDEG_FILE):
    mf = ln["mode_found"].ravel().astype(int)
    sp = ln["spoles_me"] if "spoles_me" in ln else ln["spoles"]
    g = {k: ln[k].ravel() for k in
         ("h_el", "k_el", "l_el", "h_fl", "k_fl", "l_fl",
          "h_el_tide", "k_el_tide", "l_el_tide",
          "h_fl_tide", "k_fl_tide", "l_fl_tide")}
    amp = {k: ln[k] for k in ("h_amp", "k_amp", "l_amp",
                              "h_amp_tide", "k_amp_tide", "l_amp_tide")}

    def row(vals):
        return "".join("%24.15E" % v for v in vals) + "\n"

    out = [" " + header + "\n"]
    for l in range(1, maxdeg + 1):
        i = l - 1
        nm = int(mf[i])
        out.append("%6d%6d\n" % (l, nm))
        out.append(row(sp[i, :nm]))
        out.append(row([g["h_el"][i], g["l_el"][i] * l, 0.0, 0.0, g["k_el"][i] * l]))
        out.append(row([g["h_fl"][i], g["l_fl"][i] * l, 0.0, 0.0, g["k_fl"][i] * l]))
        out.append(row(amp["h_amp"][i, :nm]))
        out.append(row(amp["l_amp"][i, :nm] * l))
        out.append(row(amp["k_amp"][i, :nm] * l))
        if l < 2:
            continue
        out.append(row([g["h_el_tide"][i], g["l_el_tide"][i] * l, 0.0, 0.0,
                        g["k_el_tide"][i] * l]))
        out.append(row([g["h_fl_tide"][i], g["l_fl_tide"][i] * l, 0.0, 0.0,
                        g["k_fl_tide"][i] * l]))
        out.append(row(amp["h_amp_tide"][i, :nm]))
        out.append(row(amp["l_amp_tide"][i, :nm] * l))
        out.append(row(amp["k_amp_tide"][i, :nm] * l))
    with open(path, "w") as f:
        f.writelines(out)


def verify_earthmodel(path, ln, norder=MAXDEG_FILE):
    """Verification only: strict re-implementation of the solver's read loop, used
    to check each written Earth-model file."""
    with open(path) as f:
        f.readline()
        toks = f.read().split()
    p = 0

    def take(n):
        nonlocal p
        v = [float(t) for t in toks[p:p + n]]
        if len(v) != n:
            raise RuntimeError("token shortfall at pos %d" % p)
        p += n
        return v

    mf = ln["mode_found"].ravel().astype(int)
    he, ke, hTE, kTE, spmax = {}, {}, {}, {}, 0.0
    for j in range(1, norder + 1):
        legord, nm = take(2)
        legord, nm = int(legord), int(nm)
        if legord != j:
            raise RuntimeError("degree out of sequence: %d != %d" % (legord, j))
        if nm != mf[j - 1]:
            raise RuntimeError("nmodes mismatch at l=%d" % j)
        s = take(nm)
        spmax = max(spmax, max(abs(x) for x in s))
        el = take(5)
        take(5)
        take(nm)          # resh
        take(nm)          # resl
        take(nm)          # resk
        he[j] = el[0]
        ke[j] = el[4] / j
        if j < 2:
            continue
        tel = take(5)
        take(5)
        take(nm)
        take(nm)
        take(nm)
        hTE[j] = tel[0]
        kTE[j] = tel[4] / j
    return dict(leftover=len(toks) - p, he=he, ke=ke, hTE=hTE, kTE=kTE,
                spmax=spmax)


def write_earthmodels():
    import scipy.io as sio
    for tag, (rel, note) in EARTH_MODELS.items():
        src = os.path.join(LN_DIR, rel)
        ln = sio.loadmat(src)
        ndeg = ln["h_el"].shape[0]
        path = os.path.join(TREE, "earthmodel", emfile(tag))
        hdr = ("%s (%s) converted from jaustermann/SLcode %s by "
               "tools/prepare_case3_nadi.py; l- and k-quantities scaled "
               "by degree per the solver's file convention; taurr/taurt/dmx/dmy = 0"
               % (tag, note, rel))
        build_earthmodel(ln, path, hdr)
        chk = verify_earthmodel(path, ln)
        print("  %-16s ndeg=%d modes<=%d  leftover=%d  h_e(2)=%+.6f k_e(2)=%+.6f "
              "h_e^T(2)=%+.6f  max|s|=%.3g kyr^-1"
              % (tag, ndeg, ln["mode_found"].max(), chk["leftover"],
                 chk["he"][2], chk["ke"][2], chk["hTE"][2], chk["spmax"]))
        assert chk["leftover"] == 0, "trailing tokens in %s" % path
        # direct cross-check against the .mat
        assert abs(chk["he"][2] - ln["h_el"].ravel()[1]) < 1e-12
        assert abs(chk["ke"][2] - ln["k_el"].ravel()[1]) < 1e-12


def main():
    global TREE, NC_ICE, GRID_DIR, TOPO_SRC, LN_DIR
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, help="output INPUT_FILES directory")
    ap.add_argument("--ice-nc", required=True, help="ICE-NADI-1.nc")
    ap.add_argument("--grid", default=None,
                    help="directory with GLlat_512.txt and GLlon_512.txt (OSF archive); if omitted or "
                         "missing, the files are generated with tools/make_grid.py")
    ap.add_argument("--topo", required=True, help="present-day topography etopo2_512_ice6gC (text)")
    ap.add_argument("--slcode", default=None,
                    help="optional: SLcode directory with SavedLN/, SavedLN_EP/ .mat files; "
                         "without it the .lucas Earth models are not written (Case 3 uses "
                         "lovenum/prem_512.l96C.ump3.lm1 instead)")
    ap.add_argument("--skip-ice", action="store_true")
    a = ap.parse_args()
    TREE, NC_ICE, GRID_DIR, TOPO_SRC, LN_DIR = a.out, a.ice_nc, a.grid, a.topo, a.slcode
    if not GRID_DIR or not os.path.isfile(os.path.join(GRID_DIR, "GLlat_512.txt")):
        import subprocess
        GRID_DIR = os.path.join(TREE, "grid_generated")
        subprocess.run([sys.executable, os.path.join(os.path.dirname(os.path.abspath(__file__)), "make_grid.py"),
                        "--outdir", GRID_DIR], check=True)
    print("== grid check ==")
    check_grid()
    print("== grid files ==")
    copy_grid()
    print("== present-day topography ==")
    write_topo()
    if LN_DIR:
        print("== earth models ==")
        write_earthmodels()
    if not a.skip_ice:
        print("== ice files ==")
        write_ice()
    print("done.")


if __name__ == "__main__":
    main()
